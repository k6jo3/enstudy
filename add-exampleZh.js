// Process a file
function processFile(filePath, translationMap) {
  let content = fs.readFileSync(filePath, 'utf-8');

  let count = 0;
  for (const [example, zh] of Object.entries(translationMap)) {
    const escapedExample = example.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    // Match: example: "..." } or example: "..." },
    const regex = new RegExp(
      `(example: "${escapedExample}")( })`,
      'g'
    );
    const replacement = `$1, exampleZh: "${zh}"$2`;
    const newContent = content.replace(regex, replacement);
    if (newContent !== content) {
      count++;
      content = newContent;
    }
  }

  // Also handle cases where the closing is }, (with comma) or just }
  // Let's try a more robust approach - match the example field followed by space/closing
  for (const [example, zh] of Object.entries(translationMap)) {
    if (content.includes(`exampleZh`) && content.includes(zh)) continue;

    const escapedExample = example.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    // Try pattern: example: "..." }
    const patterns = [
      new RegExp(`(example: "${escapedExample}")(\\s*\\})`, 'g'),
    ];

    for (const regex of patterns) {
      const newContent = content.replace(regex, `$1, exampleZh: "${zh}"$2`);
      if (newContent !== content) {
        content = newContent;
        break;
      }
    }
  }

  fs.writeFileSync(filePath, content, 'utf-8');

  // Verify
  const finalContent = fs.readFileSync(filePath, 'utf-8');
  const exampleZhCount = (finalContent.match(/exampleZh:/g) || []).length;
  const exampleCount = (finalContent.match(/example:/g) || []).length;
  console.log(`${path.basename(filePath)}: ${exampleZhCount}/${exampleCount} words have exampleZh`);
}


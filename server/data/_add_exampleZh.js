function processFile(filePath, translationMap) {
  const content = fs.readFileSync(filePath, 'utf8');

  // For each word in the translation map, add exampleZh after the example field
  let result = content;

  for (const [word, zhTranslation] of Object.entries(translationMap)) {
    // Escape special regex characters in the word
    const escapedWord = word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

    // Find the pattern: word: "word", ... example: "..." }
    // We need to add exampleZh: "..." before the closing }
    // Match the specific entry for this word and add exampleZh after example field

    // Strategy: find `example: "..."` followed by `}` for this specific word entry
    // Use a pattern that finds the word entry and adds exampleZh

    // Find: word: "exactword" ... example: "..." }
    // We look for the line containing this word and add exampleZh
    const lineRegex = new RegExp(
      `(\\bword:\\s*"${escapedWord}"[^}]*?example:\\s*"[^"]*")\\s*(\\})`,
      's'
    );

    const match = result.match(lineRegex);
    if (match) {
      const replacement = `${match[1]}, exampleZh: "${zhTranslation}" ${match[2]}`;
      result = result.replace(lineRegex, replacement);
    } else {
      console.warn(`Warning: Could not find entry for word "${word}" in ${filePath}`);
    }
  }

  fs.writeFileSync(filePath, result, 'utf8');
  console.log(`Updated ${filePath}`);
}

